# %% [markdown]
# ## 1. Что такое промпт-инжиниринг
#
# **Промпт-инжиниринг** — проектирование входных инструкций и примеров, которые
# устойчиво направляют модель к нужному поведению.
#
# Для production этого недостаточно. Нужны также:
#
# - контекст-инжиниринг;
# - выбор модели;
# - инструменты;
# - схемы и валидация;
# - тестовые наборы;
# - обработка ошибок;
# - наблюдаемость;
# - контроль версий промптов.
#
# **Промпт — часть программной системы, а не заклинание.** Его качество
# оценивают на наборе случаев, а не «на глаз».

# %% [markdown]
# ## 2. Минимальная структура сильной инструкции
#
# Практичный шаблон:
#
# ```text
# ЗАДАЧА
# Что нужно получить.
#
# КОНТЕКСТ
# Данные, определения и предметные ограничения.
#
# ПРАВИЛА
# Что разрешено, запрещено и как обрабатывать неопределённость.
#
# ФОРМАТ ОТВЕТА
# Структура, поля, объём, язык.
#
# КРИТЕРИИ КАЧЕСТВА
# Как отличить хороший результат от плохого.
# ```
#
# Не каждый запрос обязан содержать все пять заголовков. Ценность — в явном
# **контракте**, а не в ритуальной форме.

# %% [markdown]
# ### 2.1. Плохой и улучшенный запрос
#
# Плохо:
#
# ```text
# Проанализируй продажи.
# ```
#
# Проблемы: неизвестны цель, период, метрики, данные, формат и адресат.

# %% [markdown]
# Лучше — тот же запрос, но с явным контрактом (пример из конспекта):
#
# ```text
# Ты анализируешь приложенную таблицу продаж интернет-магазина за январь–июнь.
#
# Задача: найти до пяти факторов, которые сильнее всего объясняют изменение
# валовой прибыли по месяцам.
#
# Используй только поля таблицы. Не считай корреляцию причинностью.
# Для каждого вывода укажи метрику и числа, на которых он основан.
# Если данных недостаточно, отдельно перечисли ограничения.
#
# Формат:
# 1. Резюме — до 5 пунктов.
# 2. Таблица: фактор, наблюдение, числовое подтверждение, альтернативное объяснение.
# 3. Три следующих проверки.
#
# Аудитория: коммерческий директор, без ML-терминологии.
# ```

# %% [markdown]
# ## 3. Zero-shot
#
# **Zero-shot** — модель получает инструкцию без примеров решения именно этой
# задачи.
#
# ```text
# Классифицируй обращение в одну категорию: billing, delivery, technical, cancellation.
#
# Обращение: «После обновления приложение перестало открываться».
# Верни только имя категории.
# ```
#
# Ожидаемый ответ: `technical`.

# %% [markdown]
# ### 3.1. Когда zero-shot достаточно
#
# - задача стандартна и однозначна;
# - категории хорошо описаны;
# - формат прост;
# - современная модель уже умеет такой тип задач;
# - допустима небольшая вариативность.

# %% [markdown]
# ### 3.2. Как улучшить zero-shot
#
# Вместо «очень внимательно» полезнее уточнить границы:
#
# ```text
# Категория billing: списания, чеки, тарифы, возвраты денег.
# Категория technical: ошибки приложения, вход, интеграции, производительность.
# Если обращение затрагивает несколько тем, выбери причину, без устранения
# которой запрос пользователя останется нерешённым.
# ```

# %% [markdown]
# ### 3.3. Небольшой код: проверка инструкции «на глаз»
#
# Ниже — заготовка для упражнения. Она не вызывает модель (для этого нужен API —
# см. ноутбук 7), а помогает собрать промпт структурно и проверить, что в нём
# есть обязательные части.

# %%
def build_instruction(categories: dict[str, str], ticket: str) -> str:
    """Собирает текст zero-shot инструкции классификатора."""
    cats = "\n".join(f"- {name}: {desc}" for name, desc in categories.items())
    return (
        "Классифицируй обращение в одну категорию.\n\n"
        "Категории:\n"
        f"{cats}\n\n"
        "Обращение:\n"
        f"<ticket>\n{ticket}\n</ticket>\n\n"
        "Верни только имя категории."
    )

categories = {
    "billing": "платежи, чеки, возвраты денег, тарифы",
    "delivery": "сроки, адрес, курьер, выдача",
    "technical": "ошибки приложения, вход, интеграции",
    "cancellation": "явное намерение отменить заказ или подписку",
}

ticket = "После обновления приложение перестало открываться"
prompt = build_instruction(categories, ticket)
print(prompt)

# %% [markdown]
# ### 3.4. Проверка: обязательные части на месте?
#
# Напишем простую проверку того, что все категории попали в промпт и текст
# обращения отделён тегами.

# %%
def validate_prompt(prompt: str, categories: dict[str, str], ticket: str) -> list[str]:
    """Возвращает список проблем в собранном промпте."""
    issues = []
    if "<ticket>" not in prompt or "</ticket>" not in prompt:
        issues.append("нет тегов <ticket>...</ticket>")
    for name in categories:
        if name not in prompt:
            issues.append(f"категория '{name}' не упомянута")
    if ticket not in prompt:
        issues.append("текст обращения отсутствует")
    return issues


problems = validate_prompt(prompt, categories, ticket)
print("Проблемы:", problems if problems else "нет — промпт структурно корректен")

# %% [markdown]
# Это проверка **строки**, а не поведения модели. Поведение проверяется на
# eval-наборе (см. блок про evals).

# %% [markdown]
# ## 4. Few-shot
#
# **Few-shot** — в контекст включают несколько примеров входа и желаемого выхода.
# Модель продолжает продемонстрированный паттерн.
#
# ```text
# Пример 1
# Вход: «Деньги списали дважды»          -> billing
# Пример 2
# Вход: «Курьер не приехал»              -> delivery
# Пример 3
# Вход: «Хочу закрыть подписку»          -> cancellation
#
# Теперь классифицируй:
# Вход: «Не могу войти после смены пароля»
# Выход:
# ```

# %% [markdown]
# ### 4.1. Как выбирать примеры
#
# Хороший набор не должен состоять только из простых случаев. Включите:
#
# - типичный случай;
# - пограничный случай;
# - случай с недостатком данных;
# - пример запрещённой догадки;
# - пример нужного формата.

# %%
# Пример: коллекция few-shot примеров для классификации обращений.
few_shot_examples = [
    ("Деньги списали дважды", "billing"),
    ("Курьер не приехал", "delivery"),
    ("Хочу закрыть подписку, приложение работает нормально", "cancellation"),
    ("Не знаю, что за проблема, деньги ушли и товар не пришёл", "requires_human"),
]


def build_few_shot(examples: list[tuple[str, str]], test_ticket: str) -> str:
    """Собирает few-shot промпт из списка (вход, выход)."""
    lines = ["Классифицируй обращение в одну категорию.", ""]
    for i, (text, label) in enumerate(examples, start=1):
        lines.append(f"Пример {i}")
        lines.append(f"Вход: «{text}»")
        lines.append(f"Выход: {label}")
        lines.append("")
    lines.append(f"Теперь классифицируй:\nВход: «{test_ticket}»\nВыход:")
    return "\n".join(lines)


test_ticket = "Не могу войти после смены пароля"
print(build_few_shot(few_shot_examples, test_ticket))

# %% [markdown]
# ### 4.2. Ошибки few-shot
#
# - неверная метка в примере систематически «учит» неверному;
# - длинные однотипные примеры расходуют контекст;
# - порядок примеров может влиять на результат;
# - примеры могут конфликтовать с текстовыми правилами;
# - личные данные из production-примеров нельзя бездумно отправлять внешнему API.

# %% [markdown]
# ### 4.3. Few-shot для извлечения данных
#
# Третий пример может показать не только формат, но и **политику
# неопределённости**:
#
# ```text
# Текст: «Поставка осуществляется в течение 10 календарных дней»
# Ответ: {"days": 10, "status": "explicit"}
#
# Текст: «Товар будет доставлен в кратчайший срок»
# Ответ: {"days": null, "status": "not_specified"}
#
# Текст: «Поставка: 2–3 недели»
# Ответ: {"days": null, "status": "range_requires_policy"}
# ```

# %% [markdown]
# ## 5. Chain-of-thought и reasoning
#
# **Chain-of-thought** — побуждение модели генерировать промежуточные шаги
# рассуждения. Для части задач это улучшает результат.
#
# Но:
#
# - часть моделей выполняет внутреннее reasoning, которое не обязано показываться;
# - длинное правдоподобное объяснение не гарантирует, что именно оно стало
#   причиной ответа.
#
# **Практическая рекомендация:** в production требовать не «покажи все мысли»,
# а **проверяемые артефакты**:
#
# - промежуточные вычисления;
# - ссылки на использованные фрагменты;
# - перечень допущений;
# - тесты;
# - альтернативы;
# - короткое обоснование решения;
# - независимую проверку результата.

# %%
reasoning_instruction = (
    "Рассчитай итоговую стоимость.\n"
    "Покажи формулу, подставленные числа и результат.\n"
    "Отдельно проверь единицы измерения.\n"
    "Не описывай внутренний ход размышлений сверх этих проверяемых шагов."
)
print(reasoning_instruction)

# %% [markdown]
# ### 5.1. Декомпозиция вместо магии
#
# Вместо «думай по шагам» можно явно задать процесс:
#
# 1. Извлеки требования из спецификации.
# 2. Составь таблицу «требование → реализация → тест».
# 3. Найди требования без теста.
# 4. Предложи тесты только для найденных пробелов.
#
# Это делает процесс наблюдаемым и управляемым.

# %% [markdown]
# ### 5.2. Self-consistency
#
# Можно сгенерировать несколько независимых решений и сравнить. Метод повышает
# стоимость и **не** гарантирует истину: несколько прогонов могут повторять одну
# систематическую ошибку. Полезен только вместе с проверкой.

# %% [markdown]
# ## 6. Role-based prompting
#
# Роль задаёт полезный prior на лексику, перспективу анализа, критерии, глубину
# и адресата.
#
# ```text
# Ты — senior backend-разработчик, проводящий ревью Python API.
# Сосредоточься на корректности, транзакциях, обработке ошибок и тестируемости.
# Не комментируй стиль, если он не создаёт риск дефекта.
# ```

# %% [markdown]
# ### 6.1. Роль не создаёт компетентность
#
# «Ты лучший юрист мира» не даёт модели доступа к актуальному законодательству
# и не повышает автоматически достоверность. Роль должна **уточнять задачу**,
# а не заменять данные и проверку.
#
# Слабо: «Ты гениальный аналитик. Сделай идеальный анализ».
#
# Сильнее:
#
# ```text
# Действуй как продуктовый аналитик. Отделяй наблюдение от гипотезы,
# не выводи причинность из корреляции, для каждого вывода указывай метрику,
# сегмент и период сравнения.
# ```

# %% [markdown]
# ## 7. Инструкция как контракт
#
# | Компонент | Вопрос |
# |---|---|
# | Цель | Какой результат нужен и зачем? |
# | Вход | Какие данные — источник истины? |
# | Границы | Что не входит в задачу? |
# | Правила | Какие преобразования допустимы? |
# | Неопределённость | Что делать, если данных не хватает? |
# | Формат | Как машина или человек прочитает результат? |
# | Критерии | Как проверить качество? |

# %% [markdown]
# ### 7.1. Конфликты в инструкции
#
# Плохо: «Ответь максимально подробно. Ответ — не более 100 слов».
#
# Модель вынуждена угадывать приоритет. Уберите конфликт или задайте порядок:
#
# ```text
# Приоритет: корректность → соблюдение JSON Schema → краткость.
# Комментарий explanation — не более 100 слов.
# ```

# %% [markdown]
# ### 7.2. Позитивные и негативные ограничения
#
# Одного «не делай X» иногда недостаточно — укажите замену:
#
# ```text
# Не выдумывай отсутствующее значение. Вместо этого верни null
# и добавь код причины missing_source_data.
# ```

# %% [markdown]
# ## 8. Итоги ноутбука
#
# - Промпт — это контракт, а не заклинание: цель, вход, правила, формат, критерии.
# - Zero-shot достаточно для стандартных задач, few-shot — когда нужно задать
#   границы классов, формат и политику неопределённости.
# - Ценность CoT — в проверяемых артефактах, а не в «покажи все мысли».
# - Роль задаёт перспективу, но не даёт компетентность и полномочия.
# - Конфликтующие требования в инструкции нужно разрешать явным приоритетом.
