# %% [markdown]
# ## 1. Импорты и подготовка

# %%
import numpy as np
import matplotlib.pyplot as plt

rng = np.random.default_rng(42)

# %% [markdown]
# ## 2. Общий путь данных
#
# Упрощённый поток для decoder-only LLM:
#
# 1. текст → токенизатор → идентификаторы токенов;
# 2. идентификаторы → обучаемые векторы **embedding**;
# 3. к векторам добавляется информация о позиции;
# 4. последовательность проходит через много transformer-блоков;
# 5. последний слой выдаёт **logits** следующего токена;
# 6. алгоритм декодирования выбирает токен;
# 7. шаги повторяются до стоп-условия.

# %% [markdown]
# ## 3. Embeddings внутри LLM
#
# Идентификатор токена — просто номер. Перед вычислениями номер переводится в
# плотный вектор (embedding). В процессе обучения геометрия этих представлений
# настраивается так, чтобы быть полезной для предсказания продолжения.
#
# **Важно не переупрощать:** один статический token-embedding — ещё не «значение
# слова». После каждого слоя представление токена становится **контекстным**:
# токен `ключ` в текстах про замок, словарь и API получает разные внутренние
# состояния.

# %% [markdown]
# ### 3.1. Маленькая симуляция embeddings
#
# Покажем идею на игрушечном примере: пусть у нас `N=6` «слов» и каждому
# соответствует вектор размерности `d=8`. Это **не** полноценный token-embedding,
# а лишь иллюстрация: дальше эти векторы обрабатывают слои внимания.

# %%
words = ["Анна", "положила", "ноутбук", "в", "рюкзак", ","]

# Случайные векторы с фиксированным сидом — только для визуализации.
embeddings = rng.normal(0, 1, size=(len(words), 8))

print(f"Матрица embeddings: форма {embeddings.shape} ({len(words)} токенов x 8 признаков)")
print("Первая строка (токен 'Анна'):")
print(embeddings[0])

# %% [markdown]
# Настоящий embedding у большой модели имеет размерность сотни–тысячи значений,
# а не 8. Здесь 8 взяты лишь ради наглядной тепловой карты.

# %%
plt.figure(figsize=(10, 4))
plt.imshow(embeddings, aspect="auto", cmap="coolwarm")
plt.colorbar(label="значение признака")
plt.yticks(range(len(words)), words)
plt.xlabel("признак embedding")
plt.title("Пример матрицы embeddings (игрушечный, d=8)")
plt.show()

# %% [markdown]
# ## 4. Self-attention
#
# Self-attention позволяет каждому положению «найти», какая информация из других
# положений важна для обновления его представления. Для каждого токена
# формируются три вектора:
#
# - **Query (Q)** — что текущая позиция ищет;
# - **Key (K)** — по каким признакам её можно найти;
# - **Value (V)** — какую информацию она передаёт.
#
# $$Attention(Q,K,V)=softmax\left(\frac{QK^T}{\sqrt{d_k}}\right)V$$
#
# Интуиция:
#
# 1. Query сравнивается с keys (скалярные произведения);
# 2. получаются веса внимания (softmax);
# 3. values смешиваются с этими весами.

# %% [markdown]
# ### 4.1. Мини-симуляция внимания
#
# Возьмём три токена и посчитаем веса внимания к фиктивным Q/K. Это **упрощённая
# демонстрация**, реальная матрица весов arises из обучения, а не из сценария.

# %%
tokens_att = ["ноутбук", "рюкзак", "он"]
d_k = 2

# Фиктивные векторы Q, K и V (сгенерированы сидом — только для показа).
Q = rng.normal(0, 1, size=(len(tokens_att), d_k))
K = rng.normal(0, 1, size=(len(tokens_att), d_k))
V = rng.normal(0, 1, size=(len(tokens_att), d_k))

scores = Q @ K.T / np.sqrt(d_k)
weights = np.exp(scores - scores.max(axis=1, keepdims=True))
weights = weights / weights.sum(axis=1, keepdims=True)

print("Матрица весов внимания (строки = текущий токен, столбцы = контекст):")
print(weights.round(3))# %%
plt.figure(figsize=(7, 5))
plt.imshow(weights, cmap="Blues")
plt.xticks(range(len(tokens_att)), tokens_att)
plt.yticks(range(len(tokens_att)), tokens_att)
plt.xlabel("внимание к (context)")
plt.ylabel("текущий токен")
plt.title("Веса self-attention (игрушечная демонстрация)")
plt.colorbar()
plt.show()

# %% [markdown]
# **Языковой пример.** В предложении
#
# > Анна положила ноутбук в рюкзак, потому что он был прочным.
#
# модели полезно связать `он` с `рюкзак`, а не с `ноутбук`. Attention даёт
# механизм передачи релевантной информации между позициями. Это **не** отдельный
# символьный модуль разрешения местоимений — нужное поведение возникает из
# обучения многих слоёв и голов внимания.

# %% [markdown]
# ### 4.2. Causal mask
#
# В авторегрессионной decoder-only модели позиция не должна видеть будущие
# токены во время предсказания. **Causal mask** запрещает attention к позициям
# справа. Покажем, как маска обнуляет «будущее» в матрице внимания.

# %%
seq_len = 4
mask = np.triu(np.ones((seq_len, seq_len)), k=1).astype(int)
print("Causal mask (1 = запрещено смотреть вперёд):")
print(mask)

# %% [markdown]
# ## 5. Multi-head attention
#
# Вместо одного механизма внимания параллельно работают несколько **голов**.
# Разные головы могут специализироваться на разных отношениях: локальном
# синтаксисе, дальних зависимостях, повторении шаблона, структуре кода.
#
# Не стоит приписывать каждой голове одно стабильное «человеческое» значение —
# интерпретируемость attention сложнее такой картинки.

# %% [markdown]
# ## 6. Зачем нужна позиционная информация
#
# Без информации о порядке набор токенов `собака укусила человека` был бы
# слишком похож на `человек укусил собаку`. Transformer должен знать
# относительное или абсолютное положение элементов.
#
# Подходы: абсолютные позиционные эмбеддинги, sinusoidal encoding, rotary
# (RoPE), относительные смещения и другие.
#
# Для курса достаточно понимать: **содержание токена и его место кодируются
# совместно**, а конкретная техника зависит от архитектуры.

# %% [markdown]
# ## 7. Feed-forward network, residual и normalization
#
# - **Attention** условно можно представить как «собрать нужную информацию из
#   контекста».
# - **MLP** (feed-forward) — «преобразовать собранное представление».
# - **Residual connection** добавляет вход блока к его выходу — облегчает
#   обучение глубоких сетей.
# - **Normalization** стабилизирует масштабы активаций.
#
# Реальная граница функций не настолько строгая.

# %% [markdown]
# ## 8. Почему attention дорогой
#
# Для стандартного полного attention объём матрицы взаимодействий растёт
# примерно **квадратично** с длиной последовательности: удвоение контекста в ~4
# раза увеличивает работу.

# %%
lengths = np.array([512, 1024, 2048, 4096, 8192])
work = lengths ** 2  # условная мера стоимости full attention

plt.figure(figsize=(8, 4))
plt.plot(lengths, work, marker="o")
plt.xlabel("длина последовательности (токенов)")
plt.ylabel("условная стоимость full attention (усл. ед.)")
plt.title("Квадратичный рост стоимости attention")
plt.grid(True)
plt.show()

print("Соотношение: 8192/4096 =", lengths[-1] / lengths[-2],
      "по длине, а работа выросла в раз:", int(work[-1] / work[-2]))

# %% [markdown]
# Реальные системы используют оптимизированные kernels, KV-cache,
# grouped-query attention, sliding-window и другие методы — поэтому фактическая
# производительность сложнее простой квадратичной формулы.

# %% [markdown]
# ### 8.1. KV-cache при генерации
#
# При авторегрессионной генерации предыдущие **key** и **value** можно сохранить
# и не пересчитывать полностью для каждого нового токена. Это и есть **KV-cache**.
#
# Плюсы: быстрее генерировать продолжение.
# Цена: cache занимает память и растёт с длиной контекста и числом
# параллельных последовательностей.
#
# Симуляция роста размера cache (каждый новый токен добавляет K и V):

# %%
seq = np.arange(1, 11)
cache_size = 2 * seq  # два значения (K и V) на каждый новый токен

plt.figure(figsize=(8, 4))
plt.plot(seq, cache_size, marker="o")
plt.xlabel("номер сгенерированного токена")
plt.ylabel("размер KV-cache (усл. ед.)")
plt.title("Рост KV-cache при генерации")
plt.grid(True)
plt.show()

# %% [markdown]
# ## 9. Плотные модели и Mixture-of-Experts
#
# ### 9.1. Плотная (dense) модель
#
# В плотной модели для каждого токена активируется практически один и тот же
# полный набор слоёв и параметров блока. Если модель имеет 30 млрд параметров,
# большая их часть участвует в обработке каждого токена.
#
# Плюсы: простота, предсказуемое выполнение, меньше сложности маршрутизации.
# Минусы: увеличение параметров обычно увеличивает вычисления на токен.

# %% [markdown]
# ### 9.2. MoE-модель
#
# В **Mixture-of-Experts** часть MLP-блоков заменяется набором expert-сетей.
# Router для каждого токена выбирает небольшое число экспертов (например,
# top-1 или top-2).
#
# Условный пример: всего 64 эксперта, для одного токена активны 2, attention и
# общие слои работают всегда. Так можно увеличить **общее** число параметров
# без пропорционального роста вычислений на токен.

# %%
total_experts = 64
active_per_token = 2
active_ratio = active_per_token / total_experts

print(f"Всего экспертов: {total_experts}")
print(f"Активных на токен: {active_per_token}")
print(f"Доля активных экспертов: {active_ratio:.1%}")

# %% [markdown]
# ### 9.3. Total parameters и active parameters
#
# Для MoE нужно различать:
#
# - **total parameters** — все параметры модели;
# - **active parameters per token** — параметры, реально задействованные для
#   данного токена.
#
# Фраза «модель на 200 млрд параметров» без указания архитектуры мало говорит о
# стоимости инференса: MoE на 200B total / 20B active не эквивалентна ни плотной
# 200B, ни плотной 20B.

# %% [markdown]
# ### 9.4. Типичное заблуждение
#
# > «Если активны только 20 млрд параметров, достаточно памяти для 20 млрд».
#
# Обычно это **неверно**. Все веса экспертов должны где-то храниться — в VRAM,
# RAM или на других устройствах. «Активные параметры» описывают вычисления на
# токен, а не объём хранения.

# %%
total_params_b = 200
active_params_b = 20
print(f"MoE: всего {total_params_b} млрд параметров, активно {active_params_b} млрд на токен.")
print("Хранить при локальном запуске приходится все", total_params_b, "млрд весов.")

# %% [markdown]
# ### 9.5. Сравнение dense и MoE
#
# | Свойство | Dense | MoE |
# |---|---|---|
# | Параметры на токен | почти все | выбранные эксперты + общие слои |
# | Хранение весов | все | также все |
# | Реализация инференса | проще | сложнее |
# | Масштабирование ёмкости | дороже по FLOPs | выгоднее по FLOPs, но сложнее системно |
# | Несколько GPU | обычно проще | может требовать all-to-all обмена |

# %% [markdown]
# ## 10. Итоги ноутбука
#
# - Трансформер переводит токены в эмбеддинги, обменивается информацией через
#   attention и преобразует представления через MLP.
# - Attention требует позиционной информации, а causal mask запрещает «взгляд
#   вперёд» при генерации.
# - Attention квадратично дорогой — отсюда KV-cache и другие оптимизации.
# - MoE увеличивает ёмкость без пропорционального роста вычислений, но требует
#   хранить все веса.
