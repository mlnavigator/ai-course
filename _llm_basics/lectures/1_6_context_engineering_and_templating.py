#
# ```text
# prompt_id: ticket_classifier
# prompt_version: 1.3.0
# model: из конфигурации запуска
# schema_version: 2
# ```
#
# Изменение промпта — изменение поведения системы. Его проводят через тесты и
# A/B-проверку, а не незаметным редактированием production-строки.

