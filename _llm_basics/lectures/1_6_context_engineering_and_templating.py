# %% [markdown]
# ## 1. Промпт- vs контекст-инжиниринг
#
# - **Промпт-инжиниринг**: как сформулировать инструкцию.
# - **Контекст-инжиниринг**: какую информацию, в каком виде, порядке и объёме
#   дать модели.
#
# Контекст — это полный набор данных, доступных модели: инструкции, история,
# документы, примеры, описания инструментов, результаты вызовов, состояние.

# %% [markdown]
# ## 2. Контекст как собираемый объект
#
# Вместо одной строки удобно мыслить компонентами, у каждого из которых есть
# владелец, срок жизни, приоритет, лимит токенов и правила обновления.

# %%
context = {
    "policy": "правила возврата, версия 7 от 2026-08-01",
    "task": "классифицировать обращение",
    "user_profile": "VIP-клиент, история последних 5 заказов",
    "conversation_summary": "клиент жалуется на двойное списание",
    "retrieved_documents": ["инструкция по возвратам"],
    "tool_descriptions": ["get_order_status", "refund_payment"],
    "current_input": "с меня списали деньги дважды",
}

for key, value in context.items():
    print(f"{key:22} -> {value}")

# %% [markdown]
# ## 3. Критерии хорошего контекста
#
# - **релевантность** — информация нужна для текущего решения;
# - **достаточность** — есть ключевые факты и определения;
# - **непротиворечивость** — старые и новые правила не конфликтуют;
# - **происхождение** — понятно, откуда взят факт;
# - **актуальность** — данные не устарели;
# - **безопасность** — недоверенный текст не получает полномочия;
# - **компактность** — повторения и шум удалены.

# %%
def evaluate_context(ctx: dict) -> list[str]:
    """Проверяет наличие ключевых компонентов контекста."""
    required = ["policy", "task", "current_input"]
    missing = [k for k in required if not ctx.get(k)]
    return missing


print("Отсутствует:", evaluate_context(context) if evaluate_context(context) else "нет — контекст собран")

# %% [markdown]
# ## 4. Управление длинным контекстом: стратегии
#
# ### 4.1. Sliding window
#
# Оставлять последние N сообщений.
#
# Плюсы: просто. Минусы: можно потерять цель, раннее решение или ограничение.
# Годится для коротких бытовых диалогов, но опасно для длинной разработки.

# %%
def sliding_window(messages: list[str], keep_last: int = 3) -> list[str]:
    """Возвращает последние keep_last сообщений."""
    return messages[-keep_last:]


history = [f"msg{i}" for i in range(1, 8)]
print("Полная история:", history)
print("Sliding window (3):", sliding_window(history, 3))

# %% [markdown]
# ### 4.2. Суммаризация истории
#
# Старые сообщения заменяются компактной сводкой. Структурированная сводка:
#
# ```markdown
# ## Цель
# ## Ограничения
# ## Принятые решения
# ## Текущее состояние
# ## Открытые вопросы
# ## Следующие шаги
# ```
#
# **Риск:** суммаризация с потерями — ошибка в сводке становится новой «истиной».
# Меры: хранить исходную историю отдельно, не удалять критические факты,
# разделять решения и гипотезы, сохранять идентификаторы источников.

# %%
summary_template = """## Цель
{goal}

## Ограничения
{constraints}

## Принятые решения
{decisions}

## Текущее состояние
{state}

## Открытые вопросы
{open_questions}

## Следующие шаги
{next_steps}
"""

print(summary_template.format(
    goal="довести классификатор до продакшена",
    constraints="не отправлять ПДн внешнему API без минимизации",
    decisions="используем JSON Schema + локальную валидацию",
    state="реализован базовый пайплайн",
    open_questions="нужен ли refund_payment в этом спринте",
    next_steps="собрать eval-набор",
))

# %% [markdown]
# ### 4.3. Retrieval (RAG-подход)
#
# Не передавать все материалы — по запросу найти релевантные фрагменты и добавить
# top-k. Подробно — в следующем блоке. Риски: нужный фрагмент не найден, найден
# похожий, но неверный, фрагмент лишён контекста.

# %%
documents = {
    "pol1": {"text": "Возврат без чека — только в течение 14 дней", "date": "2026-08-01"},
    "pol5": {"text": "Возврат по чеку — в течение 30 дней", "date": "2026-07-15"},
}

def top_k_context(query: str, docs: dict, k: int = 1):
    """Игрушечный retrieval: просто выбирает первые k по имени."""
    # В реальности здесь стоят эмбеддинги и векторный поиск.
    names = list(docs.keys())[:k]
    return {n: docs[n] for n in names}

print(top_k_context("возврат", documents, k=2))

# %% [markdown]
# ### 4.4. Иерархическая память
#
# Разделить сведения:
#
# - короткое стабильное ядро;
# - summary текущей сессии;
# - последние сообщения без сжатия;
# - извлекаемый архив;
# - артефакты (спецификации, код, таблицы).
#
# Это практичная схема для длинноживущего агента.

# %% [markdown]
# ### 4.5. Выборочное включение инструментов
#
# Описание сотни инструментов занимает токены и усложняет выбор. Сначала
# определить класс задачи, затем подключить небольшой набор инструментов.

# %%
TOOL_CATALOG = {
    "support": ["get_order_status", "get_order_history", "get_refund_policy"],
    "finance": ["refund_payment", "get_invoice", "init_refund"],
    "admin": ["cancel_order", "block_user", "issue_refund"],
}


def select_tools(task_type: str) -> list[str]:
    return TOOL_CATALOG.get(task_type, [])


for tt in ["support", "admin", "unknown"]:
    print(f"{tt:10} -> {select_tools(tt)}")

# %% [markdown]
# ## 5. Порядок контекста
#
# Практичный порядок:
#
# 1. стабильные правила;
# 2. задача и критерии;
# 3. релевантный контекст с источниками;
# 4. конкретный текущий ввод;
# 5. напоминание о формате результата.
#
# Не дублируйте всё в начале и конце — это расходует токены и может создавать
# перевес отдельных правил.

# %% [markdown]
# ## 6. Шаблонизация промптов
#
# Строковая конкатенация быстро приводит к ошибкам. Шаблоны дают повторяемость,
# версионирование, отделение данных от инструкции, тестируемость.

# %% [markdown]
# ### 6.1. Простой f-string

# %%
task = "Классифицировать обращение"
ticket = "После обновления приложение не запускается"

prompt_fstring = f"""
Задача: {task}

Обращение:
<ticket>
{ticket}
</ticket>

Верни одну категорию: billing, delivery, technical, cancellation.
""".strip()
print(prompt_fstring)

# %% [markdown]
# Для небольшого скрипта этого достаточно. При большом числе условий удобнее Jinja2.

# %% [markdown]
# ### 6.2. Jinja2
#
# Шаблон отделяется от данных, поддерживает циклы, условия и строгий режим
# необъявленных переменных.

# %%
from jinja2 import Environment, StrictUndefined

ticket_template = """Ты классифицируешь обращения службы поддержки.

Допустимые категории:
{% for category in categories %}
- {{ category.name }}: {{ category.description }}
{% endfor %}

Правила:
- Используй только перечисленные категории.
- Если данных недостаточно, установи requires_human=true.
{% if include_explanation %}
- Дай объяснение не длиннее {{ explanation_limit }} слов.
{% else %}
- Не добавляй объяснение.
{% endif %}

<ticket>
{{ ticket_text }}
</ticket>
"""

env = Environment(
    undefined=StrictUndefined,
    autoescape=False,
    trim_blocks=True,
    lstrip_blocks=True,
)
template = env.from_string(ticket_template)

# %% [markdown]
# ### 6.3. Рендеринг с корректными данными

# %%
rendered = template.render(
    categories=[
        {"name": "billing", "description": "Платежи и возвраты"},
        {"name": "technical", "description": "Ошибки продукта"},
    ],
    include_explanation=True,
    explanation_limit=40,
    ticket_text="Списали деньги, но подписка не включилась",
)
print(rendered)

# %% [markdown]
# ### 6.4. Зачем `StrictUndefined`
#
# Без строгого режима опечатка в имени переменной превращается в пустую строку —
# промпт останется корректным, но потеряет важное правило. `StrictUndefined`
# превращает проблему в явную ошибку.

# %%
try:
    template.render(
        categories=[],
        include_explanation=False,
        explanation_limit=0,
        ticket_tex="опечатка в имени переменной",  # так: tex, а не text
    )
except Exception as exc:
    print("Поймана ошибка StrictUndefined:")
    print(type(exc).__name__, exc)

# %% [markdown]
# ### 6.5. Безопасность шаблонов
#
# Не компилируйте шаблон, полученный от недоверенного пользователя, в
# привилегированной среде. Пользовательские данные должны передаваться как
# **значения переменных**, а не как исполняемый шаблон.

# %% [markdown]
# ### 6.6. Тестирование промпт-шаблона
#
# Минимальные проверки — только рендеринг строки. Поведение модели проверяется
# отдельным eval-набором.

# %%
def render_test_case(cat_names, include_expl, limit, ticket):
    cats = [{"name": n, "description": ""} for n in cat_names]
    return template.render(
        categories=cats,
        include_explanation=include_expl,
        explanation_limit=limit,
        ticket_text=ticket,
    )


def test_prompt_contains_ticket():
    result = render_test_case([], False, 0, "Ошибка 500")
    assert "Ошибка 500" in result
    assert "Не добавляй объяснение" in result
    return True


print("Тест рендеринга:", "OK" if test_prompt_contains_ticket() else "FAIL")

