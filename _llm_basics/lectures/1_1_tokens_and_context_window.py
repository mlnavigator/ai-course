# %% [markdown]
# ## 2. Что такое токен
#
# Языковая модель обычно не читает текст посимвольно и не оперирует готовыми
# словами. Специальный алгоритм — **токенизатор** — разбивает строку на элементы
# словаря модели, которые называются **токенами**.
#
# Токеном может быть:
#
# - целое частое слово;
# - часть слова;
# - пробел вместе с началом слова;
# - знак препинания;
# - фрагмент числа;
# - фрагмент кода;
# - отдельный байтовый фрагмент для редкого символа.

# %% [markdown]
# ### 2.1. Демонстрация на реальном токенизаторе
#
# Для примера возьмём токенизатор из семейства GPT (`cl100k_base`).
# Реальные разбиения для разных моделей отличаются, поэтому в проде токены надо
# считать именно токенизатором вашей модели, а не «на глаз».
#
# ```text
# "Контекстное окно модели" -> [ряды токенов]
# ```
#
# Попробуем показать, как токены выглядят на русском, английском, числах и emoji.
# Если библиотека `tiktoken` недоступна, ячейка переключится на простую
# эвристику — тогда результат будет только качественным, а не точным.

# %%
def load_encoder():
    """Загружаем кодировку cl100k_base.

    Возвращает кортеж (encoder, точный ли подсчёт).
    Если tiktoken недоступен или кодировку не удалось получить —
    возвращает (None, False) для перехода на эвристику.
    """
    try:
        import tiktoken
        enc = tiktoken.get_encoding("cl100k_base")
        return enc, True
    except Exception as exc:
        print(f"[предупреждение] tiktoken недоступен: {exc!r}")
        return None, False


ENCODER, TOKENIZER_AVAILABLE = load_encoder()


def count_tokens_approx(text: str) -> list[str]:
    """Эвристический «токенизатор» на случай отсутствия tiktoken.

    Грубо: слова и пунктуацию по пробелам, но это лишь демонстрация,
    а не честный подсчёт токенов модели.
    """
    import re
    tokens = re.findall(r"\S+", text)
    return tokens


def tokenize_display(text: str) -> list[str]:
    """Возвращает список токенов для показа (строковое представление)."""
    if TOKENIZER_AVAILABLE:
        return [str(t) for t in ENCODER.encode(text)]
    return count_tokens_approx(text)

# %% [markdown]
# ### 2.2. Угадай, что займёт больше токенов
#
# До запуска следующей ячейки попробуйте угадать, что займёт больше токенов:

# %%
examples = {
    "Английская фраза": "Hello world!",
    "Русская фраза": "Привет, мир!",
    "Длинное целое число": "2194837619283746",
    "Длинный идентификатор": "customer_transaction_reconciliation_status",
    "Эмодзи": "🧠⚙️🚀",
}

for name, text in examples.items():
    tokens = tokenize_display(text)
    print(f"{name:35} | {len(tokens):3d} токенов | {tokens}")

# %% [markdown]
# **Вывод:** символы, слова и токены — разные единицы. Русские слова, числа
# и emoji часто стоят больше токенов, чем кажется по числу символов.

# %% [markdown]
# ### 2.3. Почему токены важны инженеру
#
# Количество токенов определяет:
#
# - сколько текста помещается в запрос;
# - стоимость запроса у многих провайдеров;
# - время обработки входа и генерации;
# - границы контекстного окна;
# - иногда качество работы с редкими языками, числами и кодом.
#
# Грубая эвристика «один токен ≈ четыре английских символа» работает только для
# английского текста. Для русского, кода, JSON и редких символов она неверна.

# %% [markdown]
# ### 2.4. Практические последствия токенизации
#
# - **Числа.** Длинное число `18472931` разбивается на несколько токенов. Модель
#   видит не абстрактное целое, а последовательность фрагментов — поэтому
#   длинная арифметика без калькулятора или кода ненадёжна.
# - **Опечатки и редкие слова.** Редкое имя или опечатка распадаются на необычные
#   части — понимание не исчезает, но вероятность ошибки растёт.
# - **Код и JSON.** Отступы, повторяющиеся ключи и длинные идентификаторы
#   занимают контекст. Большой JSON дороже компактного представления тех же данных.
# - **Многоязычность.** Неэффективная токенизация удлиняет последовательность
#   и усложняет задачу.

# %%
samples = {
    "Число": "2194837619283746",
    "Код (Python)": "def my_long_function_name(arg1, arg2):\n    return arg1 + arg2",
    "JSON": '{"key_a": "значение 1", "key_b": "значение 2"}',
}

for name, text in samples.items():
    tokens = tokenize_display(text)
    print(f"{name:12} | {len(tokens):3d} токенов | символов: {len(text)}")

# %% [markdown]
# ## 3. Контекстное окно
#
# **Контекстное окно** — максимальное число токенов, которое модель может учесть
# в одном вычислительном эпизоде. Обычно в бюджет входят:
#
# - системные и developer-инструкции;
# - все сообщения диалога;
# - описания доступных инструментов и схемы аргументов;
# - вложенные документы после токенизации;
# - результаты предыдущих tool calls;
# - текущий запрос пользователя;
# - генерируемый ответ или зарезервированный под него лимит.
#
# Важно: заявленное окно `128 000` не значит, что можно всегда отправить ровно
# столько входных токенов и получить ещё длинный ответ.

# %% [markdown]
# ### 3.1. Контекст — не долговременная память
#
# Модель знает о задаче только то, что:
#
# 1. было закреплено в её весах;
# 2. присутствует в текущем контексте;
# 3. было получено через инструменты и добавлено в контекст.
#
# Когда приложение начинает новый запрос без истории, модель не «помнит» прошлый
# диалог. Память приложения — это отдельная логика: сохранить сообщения, извлечь
# релевантные факты, сделать сводку и снова передать их модели.

# %% [markdown]
# ### 3.2. Что происходит при переполнении
#
# Варианты зависят от клиента и провайдера:
#
# - API возвращает ошибку о превышении лимита;
# - приложение удаляет самые старые сообщения;
# - история предварительно суммаризируется;
# - документы обрезаются;
# - часть контекста извлекается поиском;
# - провайдер применяет свою compaction-логику.
#
# Нельзя молча предполагать, что «модель сама разберётся»: политику обрезки надо
# знать и тестировать.

# %% [markdown]
# ### 3.3. Большое окно не гарантирует одинакового внимания ко всему тексту
#
# Даже если текст технически помещается, модель может:
#
# - хуже использовать информацию из середины длинного контекста;
# - смешивать похожие фрагменты;
# - следовать нерелевантным инструкциям из документов;
# - упустить небольшое, но важное ограничение;
# - тратить вычисления и деньги на шум.
#
# Поэтому цель контекст-инжиниринга — не «заполнить окно», а добиться высокой доли
# **релевантного и однозначного** контекста.

# %% [markdown]
# ## 4. Практика: расчёт бюджета контекстного окна
#
# Допустим, окно модели — `32_000` токенов. Соберём его из компонентов.

# %%
WINDOW = 32_000

budget = {
    "Системная инструкция": 1_200,
    "Схемы инструментов": 2_300,
    "История диалога": 8_000,
    "Документы": 14_000,
    "Текущий запрос": 500,
    "Резерв ответа": 4_000,
    "Запас": 2_000,
}

total = sum(budget.values())
print("Расчёт бюджета контекста:")
for component, tokens in budget.items():
    print(f"  {component:22} {tokens:>7,} токенов")
print(f"  {'Итого':22} {total:>7,} токенов")
print(f"  Окно модели:            {WINDOW:>7,} токенов")
print(f"  Использовано окна:      {total / WINDOW * 100:.0f}%")

