# %% [markdown]
# ## 5. Что такое языковая модель — без лишней математики
#
# Языковая модель получает последовательность фрагментов текста — токенов — и многократно предсказывает наиболее подходящее продолжение. Во время обучения она усваивает статистические закономерности языка, множество фактов, стили, типовые структуры рассуждений и программного кода.
#
# Это объясняет одновременно её сильные и слабые стороны:
#
# - она умеет строить связный текст и переносить шаблоны между задачами;
# - она способна комбинировать известные элементы новым способом;
# - она не хранит все знания как проверенную энциклопедию;
# - правдоподобное продолжение не обязано быть истинным;
# - уверенный тон не является измерением уверенности;
# - один и тот же запрос может дать разные ответы;
# - результат зависит не только от вопроса, но и от предыдущего диалога.
#
# ### Четыре сущности, которые нельзя смешивать
#
# | Сущность | Что делает | Типичная ошибка пользователя |
# |---|---|---|
# | Языковая модель | генерирует ответ по контексту | считать ответ извлечённым из базы фактов |
# | Веб-поиск | находит актуальные страницы | считать первую найденную страницу истинной |
# | Средство выполнения кода | реально считает и обрабатывает файлы | считать, что код выполнен, если модель только показала его |
# | Deep Research | многошагово ищет, читает и синтезирует источники | считать длинный отчёт автоматически достоверным |
#
# ### Демонстрация: правдоподобие не равно знанию
#
# Отправьте в новый чат:
#
# ```text
# Кратко расскажи об эксперименте профессора Ивана Лаврентьева 1987 года,
# который доказал, что музыка повышает скорость сортировки массивов человеком.
# Если такого надёжно известного эксперимента нет, прямо скажи об этом.
# Не достраивай детали.
# ```
#
# Обсудите:
#
# 1. Попыталась ли модель принять вымышленную предпосылку?
# 2. Признала ли отсутствие данных?
# 3. Изменился ли результат в ChatGPT и Qwen?
# 4. Помогло ли явное разрешение сказать «не знаю»?
#
# Урок: формулировка может снизить риск выдумки, но не устраняет его.
#
# ---

# %%
"""Мини-модель: следующее слово выбирается по частоте биграмм.

Это не LLM, но тот же принцип: правдоподобное продолжение
не обязано быть истинным фактом.
"""

from collections import Counter, defaultdict

corpus = """
модель предсказывает следующее слово
модель предсказывает правдоподобный текст
правдоподобный текст не равен знанию
эксперимент лаврентьева не найден в корпусе
"""

tokens = corpus.lower().split()
bigrams = defaultdict(Counter)
for a, b in zip(tokens, tokens[1:]):
    bigrams[a][b] += 1


def continue_from(word: str, steps: int = 8) -> str:
    out = [word]
    current = word
    for _ in range(steps):
        dist = bigrams.get(current)
        if not dist:
            break
        current = dist.most_common(1)[0][0]
        out.append(current)
    return " ".join(out)


print("Продолжение от «модель»:")
print(" ", continue_from("модель"))
print()
print("Продолжение от «эксперимент»:")
print(" ", continue_from("эксперимент"))
print()
print("Вывод: генератор всегда выдаст *какое-то* продолжение,")
print("если слово встречалось в обучающем тексте. Это не проверка факта.")


