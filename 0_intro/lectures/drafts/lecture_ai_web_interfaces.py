# | Класс задачи | Примеры | Что обязательно проверять |
# |---|---|---|
# | Генерация | письмо, план, сценарий, код, иллюстрация | соответствие задаче, факты, права, тон |
# | Преобразование | сократить, перевести, изменить стиль, превратить текст в таблицу | потерю смысла и важных условий |
# | Извлечение | найти пункты договора, поля в документе, тезисы статьи | полноту, номера, даты, отрицания |
# | Объяснение | объяснить формулу, алгоритм, термин, ошибку в коде | фактическую корректность и уровень |
# | Классификация | разнести обращения по темам, присвоить приоритет | критерии классов и пограничные случаи |
# | Идеация | придумать варианты продукта, гипотезы, вопросы | разнообразие, реализуемость, скрытые допущения |
# | Критика | найти слабые места плана, кода или аргумента | не путать убедительность с доказательством |
# | Исследование | найти источники, сравнить позиции, собрать обзор | происхождение и качество каждого источника |
# | Работа с данными | написать расчёт, проанализировать CSV, построить график | формулы, единицы, пропуски, воспроизводимость |
