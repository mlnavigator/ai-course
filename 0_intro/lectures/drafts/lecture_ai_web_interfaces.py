# - сведения, составляющие коммерческую или государственную тайну.
#
# Безопасный учебный процесс:
#
# 1. удалить имена, адреса, телефоны и идентификаторы;
# 2. заменить реальные числа синтетическими, если точность не нужна;
# 3. использовать короткий минимальный фрагмент;
# 4. проверить правила организации и настройки хранения данных;
# 5. помнить, что удаление чата из интерфейса и политика обработки данных — не одно и то же.
#
