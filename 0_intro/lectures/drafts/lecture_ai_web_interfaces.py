# ## 12. Почему запрос «придумай идеи» слаб
#
# Без условий модель выдаёт наиболее частые и усреднённые варианты. Хороший мозговой штурм должен сначала расширить пространство идей, а затем отделить генерацию от оценки.
#
# ### Этап 1. Дивергенция — получить разные классы решений
#
# ```text
# Нужно повысить посещаемость необязательных университетских консультаций
# без введения наказаний и без дополнительного бюджета.
#
# Сначала сформулируй пять разных причин низкой посещаемости.
# Затем предложи по три решения для каждой причины.
#
# Требования к разнообразию:
# - хотя бы три решения должны менять расписание или формат;
# - хотя бы три — обратную связь;
# - хотя бы три — содержание консультаций;
# - хотя бы три — социальную динамику группы;
# - не повторяй одну идею другими словами.
#
# На этом этапе не оценивай идеи.
# ```
#
# ### Этап 2. Конвергенция — оценить по явным критериям
#
# ```text
# Теперь оцени идеи по шкале 1–5:
# - ожидаемый эффект;
# - стоимость;
# - простота запуска за две недели;
# - риск отрицательной реакции студентов;
# - проверяемость результата.
#
# Не складывай баллы механически: сначала объясни веса критериев.
# Выбери три идеи для дешёвого эксперимента и предложи метрику успеха.
# ```
#
# ### Этап 3. Поиск того, что все пропустили
#
# ```text
# Представь, что первые идеи оказались поверхностными.
# Какие скрытые предпосылки мы приняли?
# Предложи пять решений, которые нарушают хотя бы одну из этих предпосылок,
# но остаются законными и этичными.
# ```
#
# ### Приём «несколько профессиональных оптик»
#
# ```text
# Рассмотри задачу независимо с четырёх позиций:
# 1. преподаватель;
# 2. студент, совмещающий учёбу и работу;
# 3. специалист по поведенческой экономике;
# 4. администратор, которому нужны измеримые результаты.
#
# Сначала дай позицию каждого, затем укажи противоречия,
# и только после этого предложи общий вариант.
# Не изображай мнения как результаты настоящего опроса людей.
# ```
#
# Модель симулирует точки зрения, а не опрашивает реальных представителей групп.
#
# ---

# %%
"""Разнообразие идей: считаем классы, а не количество абзацев."""

ideas = [
    ("расписание", "перенести консультации на слот сразу после лекции"),
    ("расписание", "сделать гибридный короткий слот в Zoom"),
    ("обратная связь", "анонимный опрос после каждой консультации"),
    ("содержание", "разбирать только задачи из ближайшей контрольной"),
    ("социальная динамика", "закреплять мини-группы с дежурным докладчиком"),
    ("расписание", "перенести консультации на слот сразу после пары"),  # почти дубль
]

seen = set()
unique = []
for cls, text in ideas:
    key = " ".join(sorted(set(text.lower().split())))
    if key in seen:
        continue
    seen.add(key)
    unique.append((cls, text))

from collections import Counter

counts = Counter(cls for cls, _ in unique)
print("Уникальных идей:", len(unique))
print("По классам:", dict(counts))
print()
need = ["расписание", "обратная связь", "содержание", "социальная динамика"]
missing = [c for c in need if counts[c] < 1]
print("Не покрытые классы:", missing or "нет")
print("Повторы другими словами отфильтрованы по набору слов.")


