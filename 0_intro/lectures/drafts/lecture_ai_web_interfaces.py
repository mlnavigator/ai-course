# %% [markdown]
# ## 21. Эхо-камера в длинном диалоге
#
# В длинной беседе модель использует предыдущие сообщения как контекст. Если пользователь многократно утверждает одну картину мира, ответы могут всё сильнее опираться на неё. Возникает замкнутый цикл:
#
# 1. пользователь предлагает интерпретацию;
# 2. модель принимает её как контекст;
# 3. следующий ответ звучит как подтверждение;
# 4. пользователь воспринимает подтверждение как независимое мнение;
# 5. предположение превращается в «установленный факт» внутри диалога.
#
# ### Как разорвать цикл
#
# - открыть новый чат без прежней рамки;
# - описать только наблюдаемые факты;
# - попросить перечислить альтернативные объяснения;
# - попросить указать, что могло бы опровергнуть каждую версию;
# - сравнить ответ другой модели;
# - обратиться к данным, первичным источникам или реальному специалисту;
# - не использовать эмоционально комфортный ответ как свидетельство истинности.
#
# Запрос для аудита разговора:
#
# ```text
# Проведи аудит нашего диалога.
#
# Найди утверждения, которые сначала были моими предположениями,
# но позже стали использоваться как факты.
# Отдели наблюдения, интерпретации, ценностные оценки и прогнозы.
# Для каждого спорного пункта предложи альтернативное объяснение
# и данные, которыми версии можно различить.
# Не ставь психологических диагнозов.
# ```
#
# ### Почему чат-бот не стоит использовать как единственного «советчика по жизни»
#
# Проблема не в том, что ИИ никогда не может дать полезную мысль. Проблема в структуре ситуации:
#
# - бот знает только отобранную пользователем версию событий;
# - у него нет доступа к невербальному контексту и другим участникам;
# - он может подстроиться под желаемый вывод;
# - он не несёт последствий решения;
# - уверенный персональный тон создаёт ложное ощущение понимания;
# - пользователь может возвращаться только за подтверждающими ответами.
#
# Разумная роль ИИ: помочь сформулировать варианты, вопросы, критерии и контраргументы. Неразумная роль: окончательно решить, кто прав, разрывать ли отношения, увольняться ли, какое лечение выбрать или считать ли человека опасным.
#
