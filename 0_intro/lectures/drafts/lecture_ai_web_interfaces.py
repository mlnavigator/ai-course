"""Код из чата нельзя считать рабочим, пока он не выполнен.

Ниже — маленький проверяемый фрагмент в духе задачи про orders.csv:
Decimal, пропуск битой суммы, запись причины.
"""

from decimal import Decimal, InvalidOperation
from io import StringIO
import csv
import sys

raw_csv = """order_id,customer_id,amount,created_at
1,A,10.50,2026-09-01
2,A,not-a-number,2026-09-02
3,B,3.00,2026-09-03
"""

totals: dict[str, Decimal] = {}
errors = []

reader = csv.DictReader(StringIO(raw_csv))
for row in reader:
    try:
        amount = Decimal(row["amount"])
    except (InvalidOperation, KeyError) as exc:
        errors.append(f"order {row.get('order_id')}: {exc}")
        continue
    cid = row["customer_id"]
    totals[cid] = totals.get(cid, Decimal("0")) + amount

print("Суммы по клиентам:")
for cid, total in sorted(totals.items(), key=lambda x: x[1], reverse=True):
    print(f"  {cid}: {total}")
print("Ошибки:")
for e in errors:
    print(" ", e)


