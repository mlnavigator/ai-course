"""Извлечение требований — это разметка текста, а не «догадка о намерении»."""

import pandas as pd

raw = """
Система должна позволять студенту загрузить CSV с оценками.
Желательно, чтобы интерфейс был красивым.
Отчёт обязан строиться не дольше 3 секунд на 10 тысяч строк.
Пользователь, наверное, захочет тёмную тему.
"""

rows = []
for i, line in enumerate(raw.strip().split("\n"), start=1):
    line = line.strip()
    if not line:
        continue
    low = line.lower()
    if "должна" in low or "обязан" in low:
        kind = "требование"
        acceptance = "нужно уточнить" if "секунд" not in low else "время отчёта ≤ 3 с на 10k строк"
        ambiguity = "нет" if "секунд" in low else "не указан критерий приёмки"
    elif "желательно" in low or "наверное" in low:
        kind = "пожелание"
        acceptance = "нужно уточнить"
        ambiguity = "нельзя превращать в обязательное требование"
    else:
        kind = "неясно"
        acceptance = "нужно уточнить"
        ambiguity = "формулировка без модальности"
    rows.append(
        {
            "ID": f"R{i}",
            "фрагмент": line,
            "тип": kind,
            "критерий приёмки": acceptance,
            "неоднозначность": ambiguity,
        }
    )

df_req = pd.DataFrame(rows)
