"""Обезличивание перед загрузкой в публичный чат."""

import re

unsafe = """
Студент Иван Петров, тел. +7 900 123-45-67, email ivan.petrov@university.ru,
договор № 4821-А, API_KEY=sk-live-demo-not-real.
"""

patterns = [
    (r"[A-Z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}", "[EMAIL]"),
    (r"\+7[\s\-]?\d{3}[\s\-]?\d{3}[\s\-]?\d{2}[\s\-]?\d{2}", "[PHONE]"),
    (r"(API_KEY|token|password)\s*=\s*\S+", r"\1=[REDACTED]"),
    (r"договор №\s*\S+", "договор № [ID]"),
    (r"Иван Петров", "[NAME]"),
]

clean = unsafe
for pat, repl in patterns:
    clean = re.sub(pat, repl, clean, flags=re.I)

print("Было:")
print(unsafe.strip())
print("\nСтало:")
print(clean.strip())
print("\nПравило: в чат идёт только минимальный синтетический фрагмент.")


