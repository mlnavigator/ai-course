# %% [markdown]
# ## 1. Импорты и подготовка

# %%
import numpy as np
import matplotlib.pyplot as plt

# Зафиксируем генератор случайных чисел — требуется для воспроизводимости.
rng = np.random.default_rng(42)

# %% [markdown]
# ## 2. От logits к вероятностям
#
# На каждом шаге генерации модель выдаёт числовую оценку для каждого токена
# словаря — **logit**. Преобразование **softmax** превращает эти числа в
# распределение вероятностей.
#
# $$P_i = \frac{\exp(z_i / T)}{\sum_j \exp(z_j / T)}$$
#
# Здесь $T$ — температура, $z_i$ — logit токена $i$ (при $T=1$ температура
# не влияет на распределение).

# %%
def softmax(logits: np.ndarray, temperature: float = 1.0) -> np.ndarray:
    """Softmax с температурой: масштабируем логиты и нормализуем экспоненты."""
    scaled = logits / temperature
    exp = np.exp(scaled - np.max(scaled))  # вычитаем максимум для устойчивости
    return exp / exp.sum()

# %% [markdown]
# ### 2.1. Условный пример
#
# После фразы «Столица Франции —» модель дала логиты. Посмотрим, как из них
# получаются вероятности.

# %%
tokens = ["Париж", "Лион", "город", "другие"]
logits = np.array([6.0, 2.0, 1.5, 0.5])

probs = softmax(logits, temperature=1.0)
print("Токен      | логит | вероятность (T=1.0)")
for tok, logit, p in zip(tokens, logits, probs):
    print(f"{tok:9} | {logit:6.2f} | {p:.4f}")

# %% [markdown]
# ## 3. Температура
#
# Температура масштабирует логиты **до** softmax:
#
# - **низкая** температура ($T \to 0$) делает распределение «острым» — разница
#   вероятностей усиливается, чаще выбирается самый вероятный токен;
# - **высокая** температура ($T > 1$) делает распределение более «плоским» —
#   растёт разнообразие, но и риск бессмыслицы;
# - при $T=0$ некоторые провайдеры выбирают наиболее вероятный токен
#   детерминированно (это не гарантирует битовую стабильность — см. раздел 6).

# %%
fig, axes = plt.subplots(1, 3, figsize=(14, 4))

for ax, temp, title in zip(axes, [0.3, 1.0, 3.0],
                           ["T=0.3 (острое)", "T=1.0 (нейтральное)", "T=3.0 (плоское)"]):
    p = softmax(logits, temperature=temp)
    ax.bar(tokens, p)
    ax.set_title(title)
    ax.set_xlabel("токен")
    ax.set_ylabel("вероятность")
    ax.set_ylim(0, 1)

plt.tight_layout()
plt.show()

# %% [markdown]
# Видно: при низкой температуре «Париж» почти гарантирован, при высокой
# вероятности выравниваются — генерация становится разнообразнее, но менее
# предсказуемой.

# %% [markdown]
# ## 4. Top-p (nucleus sampling)
#
# При **top-p** токены сортируют по вероятности и оставляют минимальное
# множество, суммарная вероятность которого достигает порога $p$. Затем выбор
# производится только из этого множества.

# %%
def nucleus_mask(probs: np.ndarray, p: float) -> np.ndarray:
    """Возвращает булеву маску токенов, входящих в nucleus с порогом p."""
    order = np.argsort(-probs)          # сортируем по убыванию вероятности
    cumulative = np.cumsum(probs[order])
    keep_positions = cumulative <= p
    # гарантируем, что хотя бы один токен попадёт в выбор
    if not keep_positions.any():
        keep_positions[0] = True
    mask = np.zeros_like(probs, dtype=bool)
    mask[order[keep_positions]] = True
    return mask

# %%
probs_tmp = softmax(logits, temperature=1.0)
print(f"Исходные вероятности: {probs_tmp.round(3)}")
print(f"Сумма вероятностей:   {probs_tmp.sum():.3f}")

for p_threshold in [0.5, 0.9, 1.0]:
    mask = nucleus_mask(probs_tmp, p_threshold)
    chosen = [(t, pr) for t, pr, ok in zip(tokens, probs_tmp, mask) if ok]
    acc = sum(pr for _, pr in chosen)
    print(f"top_p={p_threshold}: в nucleus -> {[t for t, _ in chosen]}, "
          f"накопленная вероятность ≈ {acc:.3f}")

# %% [markdown]
# При `top_p=0.90` в nucleus попадают «Париж», «Лион» и «город» — их накопленная
# вероятность ~0.90. Токены вне nucleus не участвуют в выборке.

# %% [markdown]
# ## 5. Эффект на генерации: симуляция выборки
#
# Покажем, как температура влияет на фактические выборы, если многократно
# «генерировать» следующий токен из нашего примера.

# %%
def sample_token(probs: np.ndarray, tokens: list[str], rng_) -> str:
    """Сэмплируем один токен из распределения probs."""
    return tokens[int(rng_.choice(len(tokens), p=probs))]

print("Выборка следующего токена, 12 повторов при разных T:")
for temp in [0.3, 1.0, 3.0]:
    p = softmax(logits, temperature=temp)
    choices = [sample_token(p, tokens, rng) for _ in range(12)]
    print(f"  T={temp}: {choices}")

# %% [markdown]
# Чем выше температура — тем больше разнообразия. Но повторяемость важнее
# разнообразия в задачах, где ответ должен быть стабильным (извлечение полей,
# классификация).

